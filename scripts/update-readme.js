'use strict';

// Renders the demo-account section of README.md from scripts/seed-data.js, so
// the accounts live in one place. Neither usernames nor passwords are listed:
// only how many accounts of each role the seed creates. The seed prints the
// names and fresh random passwords once; for the live deployment they are
// shared with the evaluator privately. tests/readme.test.js fails if the
// README is out of date or names an account.
//
//   npm run readme:accounts

const fs = require('node:fs');
const path = require('node:path');
const { SEED_ACCOUNTS } = require('./seed-data');

const README = path.resolve(__dirname, '..', 'README.md');
const START = '<!-- seed-accounts:start (generated by scripts/update-readme.js — do not edit by hand) -->';
const END = '<!-- seed-accounts:end -->';

function accountsTable() {
  const count = (role) => SEED_ACCOUNTS.filter((a) => a.role === role).length;
  return [
    `The seed creates ${count('user')} user accounts and ${count('admin')} admin accounts.`,
    '',
    '_Usernames and passwords are not published. `npm run seed` prints them once in the terminal; for the live deployment they are sent to the evaluator separately._',
  ].join('\n');
}

function renderInto(readme) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error('README is missing the seed-accounts markers');
  return `${readme.slice(0, start + START.length)}\n${accountsTable()}\n${readme.slice(end)}`;
}

if (require.main === module) {
  fs.writeFileSync(README, renderInto(fs.readFileSync(README, 'utf8')));
  console.log('README.md demo accounts updated.');
}

module.exports = { renderInto, README };
