'use strict';

// Copies the self-hosted web fonts (SIL Open Font License) from node_modules
// into public/fonts and writes public/css/fonts.css. Fonts are served from our
// own origin so the Content-Security-Policy can stay at font-src 'self'.
// Run with: node scripts/vendor-fonts.js   (output is committed)

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT_FONTS = path.join(ROOT, 'public', 'fonts');
const OUT_CSS = path.join(ROOT, 'public', 'css', 'fonts.css');

const SOURCES = [
  { pkg: '@fontsource-variable/bricolage-grotesque', css: ['wght.css'], license: 'bricolage-grotesque' },
  { pkg: '@fontsource/atkinson-hyperlegible', css: ['400.css', '700.css'], license: 'atkinson-hyperlegible' },
  { pkg: '@fontsource/ibm-plex-mono', css: ['400.css', '500.css'], license: 'ibm-plex-mono' },
];
const SUBSETS = /-(latin|latin-ext)-/;

fs.mkdirSync(OUT_FONTS, { recursive: true });
fs.mkdirSync(path.dirname(OUT_CSS), { recursive: true });
const blocks = [];

for (const { pkg, css, license } of SOURCES) {
  const dir = path.join(ROOT, 'node_modules', pkg);
  for (const file of css) {
    const text = fs.readFileSync(path.join(dir, file), 'utf8');
    for (const block of text.match(/@font-face\s*{[^}]*}/g)) {
      const url = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
      if (!url || !SUBSETS.test(url)) continue;
      fs.copyFileSync(path.join(dir, 'files', url), path.join(OUT_FONTS, url));
      blocks.push(block.replace(`./files/${url}`, `/fonts/${url}`));
    }
  }
  fs.copyFileSync(path.join(dir, 'LICENSE'), path.join(OUT_FONTS, `${license}.LICENSE.txt`));
}

fs.writeFileSync(OUT_CSS, `/* Generated by scripts/vendor-fonts.js — do not edit. Fonts: SIL OFL 1.1 */\n${blocks.join('\n')}\n`);
console.log(`Wrote ${blocks.length} @font-face rules to ${path.relative(ROOT, OUT_CSS)}`);
